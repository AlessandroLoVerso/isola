import AppKit
import PonteCore

/// NSPasteboard.general: polls changeCount every 0.5 s (the normal way on macOS, very cheap), reports
/// new local copies, and writes what arrives from the other computer marking it as ours so it is
/// never sent back.
@MainActor
final class PasteboardBridge {
    enum Item {
        case text(String)
        /// PNG or TIFF bytes as found; converted to PNG off the main thread.
        case image(Data)
    }

    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    var onCopy: ((Item) -> Void)?

    private let pb = NSPasteboard.general
    private var lastSeen = 0
    /// changeCount right after Ponte wrote the pasteboard.
    private var ownChange = -1
    private var timer: Timer?

    func start() {
        lastSeen = pb.changeCount // what was there before launch is not "new"
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func tick() {
        let cc = pb.changeCount
        guard cc != lastSeen else { return }
        lastSeen = cc
        if cc == ownChange { return }
        let types = pb.types ?? []
        if types.contains(Self.concealed) || types.contains(Self.transient) || types.contains(Self.autoGenerated) { return }
        if types.contains(.fileURL) { return } // no files for now (as on Windows)
        if let s = pb.string(forType: .string) {
            onCopy?(.text(s))
        } else if let png = pb.data(forType: .png) {
            onCopy?(.image(png))
        } else if let tiff = pb.data(forType: .tiff) {
            onCopy?(.image(tiff))
        }
    }

    /// PNG bytes for what tick() found (already PNG, or TIFF to convert).
    nonisolated static func pngData(_ raw: Data) -> Data? {
        if Ponte.isPng(raw) { return raw }
        guard let rep = NSBitmapImageRep(data: raw) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    func writeIncoming(text: String) -> Bool {
        pb.clearContents()
        let ok = pb.setString(text, forType: .string)
        markOwn()
        return ok
    }

    func writeIncoming(png: Data) -> Bool {
        pb.clearContents()
        pb.declareTypes([.png, .tiff], owner: nil)
        var ok = pb.setData(png, forType: .png)
        if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation { ok = pb.setData(tiff, forType: .tiff) && ok }
        markOwn()
        return ok
    }

    /// For the pairing key: marked concealed + transient (password managers' convention).
    func writeConcealed(_ text: String) {
        pb.clearContents()
        pb.declareTypes([.string, Self.concealed, Self.transient], owner: nil)
        pb.setString(text, forType: .string)
        pb.setData(Data(), forType: Self.concealed)
        pb.setData(Data(), forType: Self.transient)
        markOwn()
    }

    private func markOwn() {
        ownChange = pb.changeCount
        lastSeen = ownChange
    }
}
