import AppKit
import CryptoKit
import ImageIO
import IsolaCore
import SwiftUI
import UniformTypeIdentifiers

/// La cronologia degli appunti: cattura, azioni dalla scheda, stato della vista.
@MainActor
final class ClipboardHistory: ObservableObject {
    /// I testi più lunghi non si tengono (mai tagliati: ciò che si rimette è ciò che si era copiato).
    static let maxTextChars = 200_000
    static let maxImageBytes = 96 * 1024 * 1024
    nonisolated static let thumbPixels = 128

    /// Tipi che i gestori di password e le app usano per dire "non ricordare".
    /// Vedi nspasteboard.org.
    static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Gestori di password: quello che si copia mentre sono in primo piano non viene ricordato.
    static let passwordManagers: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.agilebits.onepassword4", "com.agilebits.onepassword",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess", "com.apple.Passwords",
        "com.dashlane.dashlanephonefinal", "com.dashlane.Dashlane",
        "com.lastpass.LastPass", "com.lastpass.lastpassmacdesktop",
        "org.keepassxc.keepassxc", "com.keepassium.KeePassium", "com.keepassium.mac",
        "com.markmcguill.strongbox.mac", "com.markmcguill.strongbox",
        "in.sinew.Enpass-Desktop", "com.enpass.Enpass-Desktop",
        "com.nordsec.nordpass", "me.proton.pass.electron", "com.roboform.mac",
        "com.keeper.keeper", "net.antelle.keeweb",
    ]
    private static let lowerPasswordManagers = Set(passwordManagers.map { $0.lowercased() })

    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var settings = ClipboardSettings()
    @Published private(set) var hotKeyRegistered = false
    /// Filtro e ricerca della scheda (qui e non in @State: la vista può essere ricreata).
    @Published var filter: Filter = .all
    @Published var query = ""
    /// "Copiato", "Immagine non trovata"… per un secondo.
    @Published private(set) var toast: Toast?
    @Published var clearArmed = false
    /// Cambia quando la scheda si apre, per aggiornare gli orari relativi.
    @Published private(set) var now = Date()

    struct Toast: Equatable {
        var ok: Bool
        var text: String
        var id = UUID()
    }

    enum Filter: String, CaseIterable, Identifiable {
        case all, text, link, image, files
        var id: String { rawValue }
        var label: String {
            switch self {
            case .all: return "Tutto"
            case .text: return "Testo"
            case .link: return "Link"
            case .image: return "Immagini"
            case .files: return "File"
            }
        }
    }

    weak var host: IslandHost?
    private(set) var store: ClipboardStore?
    /// Sempre `.general`; un'altra solo nelle prove.
    var pasteboard: NSPasteboard = .general
    var onSettingsChanged: ((ClipboardSettings, ClipboardSettings) -> Void)?

    private var lastChangeCount = 0
    private var ownChangeCount = -1
    private var generation = 0
    private var toastWork: DispatchWorkItem?
    private var clearWork: DispatchWorkItem?
    private let thumbCache = NSCache<NSString, NSImage>()
    private let iconCache = NSCache<NSString, NSImage>()

    // MARK: ciclo di vita

    func start(host: IslandHost) {
        self.host = host
        generation += 1
        settings = host.loadSettings(ClipboardSettings.self, fallback: ClipboardSettings())
        let store = ClipboardStore(dataDir: host.dataDirectory)
        self.store = store
        items = store.load().sorted { $0.time > $1.time }
        trim()
        store.sweepOrphans(items)
        // Non ricordare quello che c'era già prima dell'avvio.
        lastChangeCount = pasteboard.changeCount
        ownChangeCount = -1
    }

    func stop() {
        generation += 1
        toastWork?.cancel(); toastWork = nil
        clearWork?.cancel(); clearWork = nil
        toast = nil
        clearArmed = false
        store?.flush()
        store = nil
        items = []
        thumbCache.removeAllObjects()
        iconCache.removeAllObjects()
        host = nil
    }

    func cardBecameVisible(_ visible: Bool) {
        if visible { now = Date() } else { clearArmed = false }
    }

    func setHotKeyRegistered(_ ok: Bool) { hotKeyRegistered = ok }

    // MARK: cattura

    /// Chiamata dal timer: un solo confronto di interi quando non è cambiato niente.
    func poll() {
        let pb = pasteboard
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard settings.enabled, host != nil, count != ownChangeCount else { return }
        capture(pb)
    }

    /// Dopo una pausa: quello che è stato copiato nel frattempo non si ricorda.
    func resync() { lastChangeCount = pasteboard.changeCount }

    private func capture(_ pb: NSPasteboard) {
        // Prima di leggere qualsiasi cosa: è un segreto?
        var types = Set((pb.types ?? []).map(\.rawValue))
        for item in pb.pasteboardItems ?? [] { types.formUnion(item.types.map(\.rawValue)) }
        if !types.isDisjoint(with: Self.secretTypes) { return }
        if let bundle = NSWorkspace.shared.frontmostApplication?.bundleIdentifier?.lowercased() {
            if Self.lowerPasswordManagers.contains(bundle) { return }
            if settings.ignoredApps.contains(where: { $0.bundleId.lowercased() == bundle }) { return }
        }

        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
           let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map { $0.standardizedFileURL.path }
            add(ClipItem(kind: .files, files: paths, hash: Self.sha(paths.joined(separator: "\n"))))
            return
        }

        if let raw = pb.string(forType: .string) {
            if raw.utf16.count > Self.maxTextChars {
                host?.log("Testo troppo lungo, non salvato")
                return
            }
            if !raw.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
                let isLink = Self.isURL(trimmed)
                let text = isLink ? trimmed : raw
                add(ClipItem(kind: isLink ? .link : .text, text: text, hash: Self.sha(text)))
                return
            }
        }

        let png = pb.data(forType: .png)
        let tiff = png == nil ? pb.data(forType: .tiff) : nil
        if let data = png ?? tiff {
            guard data.count <= Self.maxImageBytes else {
                host?.log("Immagine troppo grande, non salvata")
                return
            }
            captureImage(data, isPNG: png != nil)
        }
    }

    /// Conversione in PNG e miniatura fuori dal main thread.
    private func captureImage(_ data: Data, isPNG: Bool) {
        guard let store else { return }
        let gen = generation
        let id = UUID().uuidString
        let name = "\(id).png"
        let imageURL = store.imageURL(name)
        let thumbURL = store.imagesDir.appendingPathComponent("\(id).thumb.png")
        DispatchQueue.global(qos: .utility).async { [weak self] in
            guard let result = Self.writeImage(data, isPNG: isPNG, to: imageURL, thumb: thumbURL) else {
                DispatchQueue.main.async { self?.host?.log("Immagine non salvata") }
                return
            }
            DispatchQueue.main.async {
                guard let self else { return }
                let item = ClipItem(id: id, kind: .image, image: name,
                                    imageWidth: result.width, imageHeight: result.height, hash: result.hash)
                if gen != self.generation || self.host == nil {
                    try? FileManager.default.removeItem(at: imageURL)
                    try? FileManager.default.removeItem(at: thumbURL)
                    return
                }
                self.add(item)
            }
        }
    }

    nonisolated private static func writeImage(_ data: Data, isPNG: Bool, to url: URL, thumb: URL)
        -> (width: Int, height: Int, hash: String)? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any] else { return nil }
        let w = props[kCGImagePropertyPixelWidth] as? Int ?? 0
        let h = props[kCGImagePropertyPixelHeight] as? Int ?? 0
        guard w > 0, h > 0 else { return nil }

        let pngData: Data
        if isPNG {
            pngData = data
        } else {
            guard let image = CGImageSourceCreateImageAtIndex(src, 0, nil),
                  let encoded = encodePNG(image) else { return nil }
            pngData = encoded
        }
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: thumbPixels,
        ]
        guard let small = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary),
              let thumbData = encodePNG(small) else { return nil }
        do {
            try PrivateFiles.write(pngData, to: url)
            try PrivateFiles.write(thumbData, to: thumb)
        } catch {
            try? FileManager.default.removeItem(at: url)
            return nil
        }
        return (w, h, sha(data))
    }

    nonisolated private static func encodePNG(_ image: CGImage) -> Data? {
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, image, nil)
        guard CGImageDestinationFinalize(dest) else { return nil }
        return out as Data
    }

    private func add(_ new: ClipItem) {
        guard let store else { return }
        var item = new
        item.time = Date()
        // Lo stesso contenuto già in cronologia sale in cima (e resta fissato se lo era).
        if let i = items.firstIndex(where: { $0.kind == item.kind && $0.hash == item.hash }) {
            store.deleteFiles(item) // i file dell'immagine nuova, quella vecchia resta
            var old = items.remove(at: i)
            old.time = item.time
            items.insert(old, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        trim()
        changed()
    }

    /// Tiene al massimo `maxItems` elementi non fissati (i fissati non scadono).
    private func trim(keeping keep: String? = nil) {
        let limit = max(10, settings.maxItems)
        var unpinned = 0
        var removed: [ClipItem] = []
        items.removeAll { item in
            guard !item.pinned else { return false }
            unpinned += 1
            if unpinned > limit, item.id != keep { removed.append(item); return true }
            return false
        }
        for r in removed { store?.deleteFiles(r) }
    }

    private func changed() {
        guard let store else { return }
        let host = self.host
        store.save(items) { msg in DispatchQueue.main.async { host?.log(msg) } }
    }

    // MARK: azioni dalla scheda

    /// Rimette l'elemento negli appunti. Niente ⌘V simulato: servirebbe il permesso di Accessibilità.
    func restore(_ item: ClipItem) {
        guard let store else { return }
        let pb = pasteboard
        switch item.kind {
        case .text:
            pb.clearContents()
            pb.setString(item.text ?? "", forType: .string)
        case .link:
            let text = item.text ?? ""
            let pbItem = NSPasteboardItem()
            pbItem.setString(text, forType: .string)
            if let url = URL(string: text), url.scheme != nil { pbItem.setString(url.absoluteString, forType: .URL) }
            pb.clearContents()
            pb.writeObjects([pbItem])
        case .files:
            let urls = (item.files ?? []).filter { FileManager.default.fileExists(atPath: $0) }
                .map { URL(fileURLWithPath: $0) as NSURL }
            guard !urls.isEmpty else { showToast(ok: false, "I file non esistono più"); return }
            pb.clearContents()
            pb.writeObjects(urls)
        case .image:
            guard let name = item.image, let png = try? Data(contentsOf: store.imageURL(name)) else {
                showToast(ok: false, "Immagine non trovata"); return
            }
            let pbItem = NSPasteboardItem()
            pbItem.setData(png, forType: .png)
            if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation { pbItem.setData(tiff, forType: .tiff) }
            pb.clearContents()
            pb.writeObjects([pbItem])
        }
        ownChangeCount = pb.changeCount
        lastChangeCount = ownChangeCount

        // Riusato = il più recente.
        if let i = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: i)
            moved.time = Date()
            items.insert(moved, at: 0)
            changed()
        }
        now = Date()
        showToast(ok: true, "Copiato")
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        if !items[i].pinned { trim(keeping: item.id) }
        changed()
    }

    func delete(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        let removed = items.remove(at: i)
        store?.deleteFiles(removed)
        changed()
    }

    /// Svuota la cronologia, i fissati restano.
    func clearUnpinned() {
        let removed = items.filter { !$0.pinned }
        items.removeAll { !$0.pinned }
        for r in removed { store?.deleteFiles(r) }
        clearArmed = false
        changed()
    }

    /// Primo clic su "Svuota": chiede conferma per 3 secondi.
    func armClear() {
        clearWork?.cancel()
        clearArmed = true
        let work = DispatchWorkItem { [weak self] in self?.clearArmed = false }
        clearWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 3, execute: work)
    }

    func requestKeyboardFocus() { host?.requestKeyboardFocus() }

    private func showToast(ok: Bool, _ text: String) {
        toastWork?.cancel()
        withAnimation(.easeOut(duration: 0.16)) { toast = Toast(ok: ok, text: text) }
        let work = DispatchWorkItem { [weak self] in
            withAnimation(.easeIn(duration: 0.25)) { self?.toast = nil }
        }
        toastWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2, execute: work)
    }

    // MARK: impostazioni

    func update(_ change: (inout ClipboardSettings) -> Void) {
        let old = settings
        var s = settings
        change(&s)
        guard s != old else { return }
        settings = s
        host?.saveSettings(s)
        if s.maxItems != old.maxItems { trim(); changed() }
        if s.enabled != old.enabled { resync() }
        onSettingsChanged?(old, s)
    }

    // MARK: vista

    var visibleItems: [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        return items
            .filter { matches($0, query: q) }
            .sorted { a, b in a.pinned != b.pinned ? a.pinned : a.time > b.time }
    }

    private func matches(_ item: ClipItem, query q: String) -> Bool {
        switch filter {
        case .all: break
        case .text: if item.kind != .text { return false }
        case .link: if item.kind != .link { return false }
        case .image: if item.kind != .image { return false }
        case .files: if item.kind != .files { return false }
        }
        guard !q.isEmpty else { return true }
        let hay: String
        switch item.kind {
        case .files: hay = (item.files ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: " ")
        case .image: hay = "immagine"
        default: hay = item.text ?? ""
        }
        return hay.localizedStandardContains(q)
    }

    func thumbnail(_ item: ClipItem) -> NSImage? {
        guard item.kind == .image, let store else { return nil }
        if let cached = thumbCache.object(forKey: item.id as NSString) { return cached }
        guard let img = NSImage(contentsOf: store.thumbURL(item)) else { return nil }
        thumbCache.setObject(img, forKey: item.id as NSString)
        return img
    }

    /// Icona del Finder del primo file.
    func fileIcon(_ item: ClipItem) -> NSImage? {
        guard item.kind == .files, let first = item.files?.first else { return nil }
        if let cached = iconCache.object(forKey: first as NSString) { return cached }
        guard FileManager.default.fileExists(atPath: first) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: first)
        iconCache.setObject(icon, forKey: first as NSString)
        return icon
    }

    // MARK: utilità

    static func isURL(_ s: String) -> Bool {
        if s.count > 2048 || s.contains(where: { $0.isWhitespace }) { return false }
        if s.lowercased().hasPrefix("www.") { return s.count > 6 && s.dropFirst(4).contains(".") }
        guard let u = URL(string: s), let scheme = u.scheme?.lowercased() else { return false }
        switch scheme {
        case "mailto": return s.count > 7
        case "http", "https", "ftp": return !(u.host ?? "").isEmpty
        default: return false
        }
    }

    nonisolated static func sha(_ s: String) -> String { sha(Data(s.utf8)) }
    nonisolated static func sha(_ d: Data) -> String {
        SHA256.hash(data: d).map { String(format: "%02x", $0) }.joined().prefix(32).description
    }
}
